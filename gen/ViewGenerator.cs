using System.Linq;
using System.Text;
using System.Collections.Generic;
using System.Collections.Immutable;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Pamella.Generators;

/// <summary>
/// Generates the constructor functions and the concrete class members of the view interfaces.
/// </summary>
[Generator]
public class ViewGenerator : IIncrementalGenerator
{
    const string viewInterface = "Pamella.View";
    const string areaType = "Pamella.Area";
    const string ignoreAttribute = "Blindness.Factory.IgnoreAttribute";
    const string untrackedAttribute = "Pamella.UntrackedAttribute";
    const string defaultAttribute = "Pamella.DefaultAttribute";
    const string requiredAttribute = "Pamella.RequiredAttribute";
    const string privateAttribute = "Pamella.PrivateAttribute";
    const string constructorAttribute = "Pamella.ConstructorAttribute";
    const char separator = '\u0001';

    static readonly DiagnosticDescriptor generatedOnly = new(
        "PM001",
        "The attribute needs a generated property",
        "The property '{0}' has a body, so [{1}] cannot control it",
        "Pamella", DiagnosticSeverity.Error, true);

    static readonly DiagnosticDescriptor sameName = new(
        "PM002",
        "Two components have the same constructor name",
        "More than one component uses the constructor name '{0}'; use [Constructor] to choose another",
        "Pamella", DiagnosticSeverity.Error, true);

    static readonly DiagnosticDescriptor paintMethod = new(
        "PM003",
        "Paint is registered in Design",
        "The component '{0}' declares Paint(); call Paint(() => ...) inside Design instead",
        "Pamella", DiagnosticSeverity.Error, true);

    static readonly SymbolDisplayFormat typeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(
            SymbolDisplayMiscellaneousOptions.UseSpecialTypes |
            SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers);

    readonly struct Output(string hint, string concrete, string factoryName, string factory, string registration, string errors)
    {
        public string Hint { get; } = hint;
        public string Concrete { get; } = concrete;
        public string FactoryName { get; } = factoryName;
        public string Factory { get; } = factory;
        public string Registration { get; } = registration;
        public string Errors { get; } = errors;

        public override bool Equals(object obj)
            => obj is Output o && o.Hint == Hint && o.Concrete == Concrete
                && o.FactoryName == FactoryName && o.Factory == Factory
                && o.Registration == Registration && o.Errors == Errors;

        public override int GetHashCode()
            => (Hint + Concrete + FactoryName + Factory + Registration + Errors).GetHashCode();
    }

    sealed class Property(IPropertySymbol symbol, string type, string parameter)
    {
        public IPropertySymbol Symbol => symbol;
        public string Name => symbol.Name;
        public string Type => type;
        public string Parameter => parameter;
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output => output.AddSource(
            "Pamella.GlobalUsings.g.cs",
            SourceText.From(GlobalUsings, Encoding.UTF8)));

        var views = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is InterfaceDeclarationSyntax declaration && declaration.BaseList is not null,
                static (ctx, _) => Generate(ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) as INamedTypeSymbol))
            .Where(static view => view.HasValue)
            .Select(static (view, _) => view.Value)
            .Collect();

        var references = context.CompilationProvider
            .Select(static (compilation, _) => GenerateReferences(compilation));

        context.RegisterSourceOutput(views.Combine(references), static (output, data) =>
        {
            foreach (var code in GenerateAll(output, data.Left, data.Right))
                output.AddSource(code.Key, SourceText.From(code.Value, Encoding.UTF8));
        });
    }

    /// <summary>
    /// Get the global usings added to every project that uses the generator.
    /// </summary>
    public const string GlobalUsings = """
        // <auto-generated/>
        global using Radiance;
        global using Radiance.Primitives;
        global using Pamella;
        global using static Radiance.Utils;
        global using static Pamella.Utils;
        global using static Pamella.Generated.Components;
        """;

    static Dictionary<string, string> GenerateAll(
        SourceProductionContext output,
        ImmutableArray<Output> views,
        string references)
    {
        var files = new Dictionary<string, string>();
        var unique = views.GroupBy(v => v.Hint).Select(g => g.First()).ToList();
        foreach (var view in unique)
        {
            files[view.Hint + ".Concrete.g.cs"] = view.Concrete;
            Report(output, view.Errors);
        }

        var parts = references.Split(separator);
        var factories = new List<(string Name, string Code)>();
        factories.AddRange(unique.Where(v => v.Factory.Length > 0).Select(v => (v.FactoryName, v.Factory)));
        for (int i = 0; i + 1 < parts.Length; i += 2)
            factories.Add((parts[i], parts[i + 1]));

        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine("#nullable disable");
        code.AppendLine("namespace Pamella.Generated;");
        code.AppendLine();
        code.AppendLine("internal static partial class Components");
        code.AppendLine("{");
        foreach (var group in factories.GroupBy(f => f.Name))
        {
            var distinct = group.Select(f => f.Code).Distinct().ToList();
            if (distinct.Count == 1)
            {
                code.Append(distinct[0]);
                continue;
            }

            output.ReportDiagnostic(Diagnostic.Create(sameName, Location.None, group.Key));
        }
        code.AppendLine("}");
        files["Pamella.Components.g.cs"] = code.ToString();

        var modules = parts.Length % 2 == 1 ? parts[parts.Length - 1] : "";
        var boot = new StringBuilder();
        boot.AppendLine("// <auto-generated/>");
        boot.AppendLine("#nullable disable");
        boot.AppendLine("#pragma warning disable CA2255");
        boot.AppendLine("namespace Pamella.Generated;");
        boot.AppendLine();
        boot.AppendLine("internal static class ViewBootstrap");
        boot.AppendLine("{");
        boot.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        boot.AppendLine("    internal static void Initialize()");
        boot.AppendLine("    {");
        boot.Append(modules);
        foreach (var view in unique)
            boot.Append(view.Registration);
        boot.AppendLine("    }");
        boot.AppendLine("}");
        files["Pamella.Bootstrap.g.cs"] = boot.ToString();
        return files;
    }

    static void Report(SourceProductionContext output, string errors)
    {
        if (errors.Length == 0)
            return;

        foreach (var line in errors.Split('\n'))
        {
            var data = line.Split('|');
            var location = Location.Create(
                data[1],
                new TextSpan(int.Parse(data[2]), int.Parse(data[3])),
                default);
            var descriptor = data[0] == paintMethod.Id ? paintMethod : generatedOnly;
            output.ReportDiagnostic(Diagnostic.Create(descriptor, location, data[4], data[5]));
        }
    }

    static Output? Generate(INamedTypeSymbol node)
    {
        if (!IsView(node))
            return null;

        var types = GetHierarchy(node);
        var properties = GetProperties(types);
        var nodeName = node.ToDisplayString(typeFormat);
        var hint = node.ToDisplayString();
        var concrete = GetConcreteName(node);

        var registration = new StringBuilder();
        registration.AppendLine(
            $"        global::Pamella.ViewRegistry.Register(typeof({nodeName}), typeof({concrete}));");

        return new Output(
            hint,
            GenerateConcrete(node, types, properties),
            GetFactoryName(node),
            GenerateFactory(node, properties),
            registration.ToString(),
            GetErrors(node));
    }

    static string GenerateReferences(Compilation compilation)
    {
        var parts = new List<string>();
        var modules = new StringBuilder();
        foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols)
        {
            var usesPamella = assembly.Name == "Pamella" || assembly.Modules
                .SelectMany(m => m.ReferencedAssemblySymbols)
                .Any(a => a.Name == "Pamella");
            if (!usesPamella)
                continue;

            var views = GetTypes(assembly.GlobalNamespace)
                .Where(type => type.DeclaredAccessibility == Accessibility.Public && IsView(type))
                .ToList();
            if (views.Count == 0)
                continue;

            var olderBuild = views.Any(type => compilation.Assembly.GetTypeByMetadataName(type.ToDisplayString()) is not null);
            if (olderBuild)
                continue;

            foreach (var type in views)
            {
                parts.Add(GetFactoryName(type));
                parts.Add(GenerateFactory(type, GetProperties(GetHierarchy(type))));
            }

            modules.AppendLine(
                $"        global::Pamella.ViewRegistry.RegisterLibrary(typeof({views[0].ToDisplayString(typeFormat)}).Assembly);");
        }

        parts.Add(modules.ToString());
        return string.Join(separator.ToString(), parts);
    }

    static IEnumerable<INamedTypeSymbol> GetTypes(INamespaceSymbol space)
    {
        foreach (var type in space.GetTypeMembers())
            yield return type;

        foreach (var inner in space.GetNamespaceMembers())
            foreach (var type in GetTypes(inner))
                yield return type;
    }

    static bool IsView(INamedTypeSymbol node)
        => node is not null
            && node.TypeKind == TypeKind.Interface
            && !node.IsGenericType
            && node.ContainingType is null
            && node.AllInterfaces.Any(i => i.ToDisplayString() == viewInterface)
            && !node.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == ignoreAttribute);

    static List<INamedTypeSymbol> GetHierarchy(INamedTypeSymbol node)
        => node.AllInterfaces
            .Append(node)
            .Where(t => t.ToDisplayString() == viewInterface
                || t.AllInterfaces.Any(i => i.ToDisplayString() == viewInterface))
            .OrderBy(t => t.AllInterfaces.Length)
            .ToList();

    static List<Property> GetProperties(List<INamedTypeSymbol> types)
    {
        var used = new HashSet<string>();
        var result = new List<Property>();
        foreach (var symbol in Enumerable.Reverse(types)
            .SelectMany(t => t.GetMembers().OfType<IPropertySymbol>())
            .Where(p => !p.IsStatic && !p.IsIndexer && p.IsAbstract && p.SetMethod is not null))
        {
            if (!used.Add(symbol.Name))
                continue;

            result.Add(new Property(
                symbol,
                symbol.Type.ToDisplayString(typeFormat),
                GetParameterName(symbol.Name)));
        }

        return result;
    }

    static string GetParameterName(string property)
    {
        if (property == "LocalX")
            return "x";

        if (property == "LocalY")
            return "y";

        var name = char.ToLowerInvariant(property[0]) + property.Substring(1);
        return SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;
    }

    static bool Has(ISymbol symbol, string attribute)
        => symbol.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == attribute);

    static string GetConcreteName(INamedTypeSymbol node)
        => node.ContainingNamespace.IsGlobalNamespace
            ? $"global::{node.Name}Concrete"
            : $"global::{node.ContainingNamespace.ToDisplayString()}.{node.Name}Concrete";

    static string GetFactoryName(INamedTypeSymbol node)
    {
        var attribute = node.GetAttributes()
            .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == constructorAttribute);
        return attribute?.ConstructorArguments[0].Value as string ?? node.Name;
    }

    static string GetErrors(INamedTypeSymbol node)
    {
        var errors = new List<string>();
        foreach (var property in node.GetMembers().OfType<IPropertySymbol>().Where(p => !p.IsAbstract))
        {
            foreach (var (attribute, label) in new[] { (untrackedAttribute, "Untracked"), (requiredAttribute, "Required"), (privateAttribute, "Private") })
            {
                if (!Has(property, attribute))
                    continue;

                var location = property.Locations[0];
                errors.Add($"{generatedOnly.Id}|{location.SourceTree?.FilePath}|{location.SourceSpan.Start}|{location.SourceSpan.Length}|{property.Name}|{label}");
            }
        }

        foreach (var method in node.GetMembers("Paint").OfType<IMethodSymbol>().Where(m => !m.IsAbstract && m.Parameters.Length == 0))
        {
            var location = method.Locations[0];
            errors.Add($"{paintMethod.Id}|{location.SourceTree?.FilePath}|{location.SourceSpan.Start}|{location.SourceSpan.Length}|{node.Name}|");
        }

        return string.Join("\n", errors);
    }

    static IEnumerable<(INamedTypeSymbol Type, IMethodSymbol Method)> Find(
        List<INamedTypeSymbol> types, string name, int parameters = 0)
        => types.SelectMany(t => t.GetMembers(name)
            .OfType<IMethodSymbol>()
            .Where(m => !m.IsStatic && !m.IsAbstract && m.Parameters.Length == parameters)
            .Select(m => (t, m)));

    static bool ReturnsTask(IMethodSymbol method)
        => method.ReturnType.ToDisplayString() == "System.Threading.Tasks.Task";

    static string GenerateConcrete(INamedTypeSymbol node, List<INamedTypeSymbol> types, List<Property> properties)
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine("#nullable disable");
        if (!node.ContainingNamespace.IsGlobalNamespace)
            code.AppendLine($"namespace {node.ContainingNamespace.ToDisplayString()};");
        code.AppendLine();
        code.AppendLine($"partial class {node.Name}Concrete");
        code.AppendLine("{");

        AppendSequence(code, types, "Design", "CallDesign");
        AppendSequence(code, types, "Behaviour", "CallBehaviour");
        AppendSequence(code, types, "Reloaded", "CallReloaded");
        AppendAsync(code, types, "State", "CallState", false);
        AppendAsync(code, types, "Load", "CallLoad", true);
        AppendAsync(code, types, "Unload", "CallUnload", true);
        AppendLast(code, types);
        AppendInvalidation(code, properties);

        code.AppendLine("}");
        return node.ContainingAssembly.Name == "Pamella"
            ? code.Replace("protected override", "protected internal override").ToString()
            : code.ToString();
    }

    static void AppendSequence(StringBuilder code, List<INamedTypeSymbol> types, string method, string target)
    {
        var found = Find(types, method).Where(m => m.Method.ReturnsVoid).ToList();
        if (found.Count == 0)
            return;

        code.AppendLine($"    protected override void {target}()");
        code.AppendLine("    {");
        foreach (var (type, _) in found)
            code.AppendLine($"        (({type.ToDisplayString(typeFormat)})this).{method}();");
        code.AppendLine("    }");
    }

    static void AppendAsync(StringBuilder code, List<INamedTypeSymbol> types, string method, string target, bool hidden)
    {
        var found = Find(types, method).ToList();
        if (found.Count == 0)
            return;

        code.AppendLine($"    protected override global::System.Threading.Tasks.Task {target}()");
        code.AppendLine("    {");
        code.AppendLine("        var tasks = new global::System.Collections.Generic.List<global::System.Threading.Tasks.Task>();");
        foreach (var (type, symbol) in found)
        {
            var name = type.ToDisplayString(typeFormat);
            if (hidden)
                code.AppendLine($"        tasks.Add(InvokeHidden(typeof({name}), \"{method}\"));");
            else if (ReturnsTask(symbol))
                code.AppendLine($"        tasks.Add((({name})this).{method}());");
            else code.AppendLine($"        (({name})this).{method}();");
        }
        code.AppendLine("        return Join(tasks);");
        code.AppendLine("    }");
    }

    static void AppendLast(StringBuilder code, List<INamedTypeSymbol> types)
    {
        var ticks = Find(types, "Tick", 1)
            .Where(m => m.Method.ReturnsVoid && m.Method.Parameters[0].Type.SpecialType == SpecialType.System_Single)
            .ToList();
        if (ticks.Count > 0)
        {
            code.AppendLine("    protected override bool HasTick => true;");
            code.AppendLine("    protected override void CallTick(float dt)");
            code.AppendLine("    {");
            foreach (var (type, _) in ticks)
                code.AppendLine($"        (({type.ToDisplayString(typeFormat)})this).Tick(dt);");
            code.AppendLine("    }");
        }

        var area = types
            .SelectMany(t => t.GetMembers("Area").OfType<IPropertySymbol>().Select(p => (Type: t, Property: p)))
            .Where(p => !p.Property.IsAbstract && !p.Property.IsStatic && p.Property.Type.ToDisplayString() == areaType)
            .LastOrDefault();
        if (area.Type is not null)
        {
            code.AppendLine("    protected override bool HasArea => true;");
            code.AppendLine($"    protected override global::Pamella.Area CallArea() => (({area.Type.ToDisplayString(typeFormat)})this).Area;");
        }
    }

    static void AppendInvalidation(StringBuilder code, List<Property> properties)
    {
        var watched = properties
            .Where(p => p.Symbol.ContainingType.ToDisplayString() != viewInterface && !Has(p.Symbol, untrackedAttribute))
            .ToList();
        if (watched.Count == 0)
            return;

        code.AppendLine("    protected override void WireInvalidation()");
        code.AppendLine("    {");
        foreach (var property in watched)
            code.AppendLine($"        Watch<{property.Type}>(\"{property.Name}\");");
        code.AppendLine("    }");
    }

    static string GenerateFactory(INamedTypeSymbol node, List<Property> properties)
    {
        var nodeName = node.ToDisplayString(typeFormat);
        var data = properties
            .Where(p => !Has(p.Symbol, privateAttribute))
            .OrderBy(p => Has(p.Symbol, requiredAttribute) ? 0 : 1)
            .ToList();

        var parameters = data.Select(p =>
        {
            var type = IsRaw(p.Symbol.Type) ? p.Type : $"global::Pamella.Bindable<{p.Type}>";
            return Has(p.Symbol, requiredAttribute)
                ? $"{type} {p.Parameter}"
                : $"{type} {p.Parameter} = default";
        });

        var code = new StringBuilder();
        foreach (var property in data)
        {
            var value = GetDefault(property.Symbol);
            if (value is not null)
            {
                code.AppendLine($"    /// <param name=\"{property.Parameter.TrimStart('@')}\">Default: {System.Security.SecurityElement.Escape(value)}</param>");
            }
        }
        code.AppendLine($"    {(node.DeclaredAccessibility == Accessibility.Public ? "public" : "internal")} static {nodeName} {GetFactoryName(node)}({string.Join(", ", parameters)})");
        code.AppendLine("    {");
        code.AppendLine($"        var view = global::Pamella.ViewFactory.Create<{nodeName}>();");
        foreach (var property in data)
            AppendArgument(code, property);
        code.AppendLine("        return view;");
        code.AppendLine("    }");
        return code.ToString();
    }

    static string GetDefault(IPropertySymbol property)
    {
        var attribute = property.GetAttributes()
            .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == defaultAttribute);
        return attribute is null ? null : attribute.ConstructorArguments[0].ToCSharpString();
    }

    static bool IsRaw(ITypeSymbol type)
        => type.TypeKind is TypeKind.Delegate or TypeKind.Array or TypeKind.Interface or TypeKind.Dynamic;

    static bool HoldsView(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol array)
            return HoldsView(array.ElementType);

        return type.ToDisplayString() == viewInterface
            || type.AllInterfaces.Any(i => i.ToDisplayString() == viewInterface);
    }

    static void AppendArgument(StringBuilder code, Property property)
    {
        var name = property.Name;
        var parameter = property.Parameter;
        var value = Has(property.Symbol, requiredAttribute) ? null : GetDefault(property.Symbol);
        var owner = property.Symbol.ContainingType.ToDisplayString(typeFormat);
        if (property.Symbol.Type.TypeKind == TypeKind.Dynamic)
        {
            code.AppendLine($"        if ({parameter} is global::Pamella.IBindable)");
            code.AppendLine("        {");
            code.AppendLine($"            ((global::Pamella.IBindable)(object){parameter}).ApplyTo(view, typeof({owner}), \"{name}\");");
            code.AppendLine($"            global::Pamella.ViewFactory.MarkArgument(view, \"{name}\");");
            code.AppendLine("        }");
            code.AppendLine($"        else if ({parameter} is not null)");
            code.AppendLine("        {");
            code.AppendLine($"            view.{name} = {parameter};");
            code.AppendLine($"            global::Pamella.ViewFactory.MarkArgument(view, \"{name}\");");
            code.AppendLine("        }");
            return;
        }

        if (IsRaw(property.Symbol.Type))
        {
            code.AppendLine($"        if ({parameter} is not null)");
            code.AppendLine("        {");
            code.AppendLine($"            view.{name} = {parameter};");
            code.AppendLine($"            global::Pamella.ViewFactory.MarkArgument(view, \"{name}\");");
            if (HoldsView(property.Symbol.Type))
                code.AppendLine($"            global::Pamella.ViewFactory.Adopt(view, {parameter});");
            code.AppendLine("        }");
            return;
        }

        code.AppendLine($"        if ({parameter}.HasValue)");
        code.AppendLine("        {");
        code.AppendLine($"            view.{name} = {parameter}.Value;");
        code.AppendLine($"            global::Pamella.ViewFactory.MarkArgument(view, \"{name}\");");
        code.AppendLine("        }");
        code.AppendLine($"        else if ({parameter}.IsBound)");
        code.AppendLine("        {");
        code.AppendLine($"            global::Pamella.ViewFactory.Bind(view, typeof({owner}), \"{name}\", {parameter}.Source);");
        code.AppendLine($"            global::Pamella.ViewFactory.MarkArgument(view, \"{name}\");");
        code.AppendLine("        }");
        if (value is not null)
            code.AppendLine($"        else view.{name} = {value};");
    }
}
